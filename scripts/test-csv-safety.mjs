import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const source = fs.readFileSync(new URL('../assets/js/csv-safety.js', import.meta.url), 'utf8');
const context = { window: {} };
vm.runInNewContext(source, context);
const csv = context.window.PraviCSV;
assert.equal(csv.cell('=1+1'), `"'=1+1"`);
assert.equal(csv.cell('  @SUM(A1:A2)'), `"'  @SUM(A1:A2)"`);
assert.equal(csv.cell('client, "one"'), '"client, ""one"""');
assert.equal(csv.cell(-123.45), '"-123.45"');
assert.equal(csv.cell('normal text'), '"normal text"');
assert.equal(csv.cell('=SUM(A1:A2)'), `"'=SUM(A1:A2)"`);
assert.equal(csv.cell('+cmd|calc'), `"'+cmd|calc"`);
assert.equal(csv.cell('-1+cmd'), `"'-1+cmd"`);
assert.equal(csv.cell('-123'), '"-123"');
assert.equal(csv.cell('\t=1+1'), `"'\t=1+1"`);
assert.equal(csv.serialize([['Name', 'Value'], ['Test', '=HYPERLINK("x")']]).charCodeAt(0), 0xFEFF);
console.log('CSV safety tests passed (formula-like text, quoting, numeric negatives, BOM).');
